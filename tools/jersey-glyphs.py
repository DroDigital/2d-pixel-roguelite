#!/usr/bin/env python3
"""Cut the game's Latin glyphs from Jersey 10 (SIL OFL 1.1, (c) 2023 The Soft Type Project Authors) into src/game/lang/jersey.js.

Jersey 10 is drawn on a pixel grid of 75 units: 10 px capitals with 2 px strokes. The glyphs are cut at that native
size. The game's text layer has twice the game's resolution, so there a capital is 5 game pixels tall (the size of
the old 3x5 font) with all of Jersey's detail.

    pip install fonttools brotli
    python3 tools/jersey-glyphs.py      (downloads the font from npm the first time)
"""
import io, json, os, tarfile, urllib.request
from fontTools.ttLib import TTFont
from fontTools.pens.pointInsidePen import PointInsidePen

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
CACHE = os.path.join(ROOT, "node_modules", ".cache", "jersey-10")
PKG = "https://registry.npmjs.org/@fontsource/jersey-10/-/jersey-10-5.3.0.tgz"
U = 75  # font units per pixel
# what the game draws: capitals (text is upper-cased), digits, punctuation, the accented capitals the translations
# use, and "x" (the pixelfx combo counter's multiplier)
CHARS = (
    "".join(chr(c) for c in range(33, 127) if not ("a" <= chr(c) <= "z")) + "x"
    + "ÀÁÂÃÄÅÆÇÈÉÊËÌÍÎÏÑÒÓÔÕÖØÙÚÛÜÝŸŒ¡¿«»·…–—’"
)


def fonts():
    os.makedirs(CACHE, exist_ok=True)
    out = []
    for sub in ("latin", "latin-ext"):
        path = os.path.join(CACHE, f"{sub}.woff2")
        if not os.path.exists(path):
            data = urllib.request.urlopen(PKG).read()
            with tarfile.open(fileobj=io.BytesIO(data)) as tar:
                for m in tar.getmembers():
                    for s in ("latin", "latin-ext"):
                        if m.name.endswith(f"/jersey-10-{s}-400-normal.woff2"):
                            open(os.path.join(CACHE, f"{s}.woff2"), "wb").write(tar.extractfile(m).read())
        out.append(TTFont(path))
    return out


def ink(f, ch):
    gs, cmap = f.getGlyphSet(), f.getBestCmap()
    name = cmap.get(ord(ch))
    if not name:
        return None
    adv = round(f["hmtx"][name][0] / U)
    pts = {}
    for yb in range(-4, 14):
        for x in range(adv + 1):
            pen = PointInsidePen(gs, ((x + 0.5) * U, (yb + 0.5) * U))
            gs[name].draw(pen)
            if pen.getResult():
                pts[(x, yb)] = True
    return adv, pts


def encode(ch, w, oy, rows):
    return f"{ch}:{w},{oy}," + ",".join(format(sum(1 << x for x, on in enumerate(r) if on), "x") for r in rows)


def cut(adv, pts, cap_bottom):
    """Rows from the glyph's top ink row down; the top row's offset places the capitals' bottom row at cap_bottom."""
    w = max(adv - 1, max([x for x, _ in pts] + [-1]) + 1)
    ys = [y for _, y in pts] or [0]
    top, low = max(ys), min(ys)
    rows = [[(x, y) in pts for x in range(w)] for y in range(top, low - 1, -1)]
    return w, cap_bottom - top, rows


def main():
    fs = fonts()
    hi, missing = [], []
    for ch in CHARS:
        got = next((r for r in (ink(f, ch) for f in fs) if r), None)
        if not got:
            missing.append(ch)
            continue
        adv, pts = got
        if not pts:
            continue
        hi.append(encode(ch, *cut(adv, pts, 9)))
    space = round(fs[0]["hmtx"][fs[0].getBestCmap()[32]][0] / U)
    if missing:
        print("not in Jersey 10:", "".join(missing))
    data = {"space": space, "glyphs": "|".join(hi)}
    head = ("// Generated by tools/jersey-glyphs.py from Jersey 10 (SIL Open Font License 1.1, (c) 2023 The Soft Type Project Authors).\n"
            "// \"char:width,top row,row bits...\" per glyph; capitals sit on rows 0-9. Do not edit by hand.\n")
    open(os.path.join(ROOT, "src", "game", "lang", "jersey.js"), "w", encoding="utf8").write(
        head + "export const JERSEY = " + json.dumps(data, ensure_ascii=False) + ";\n")
    print(f"{len(hi)} glyphs, space {space}")


main()
