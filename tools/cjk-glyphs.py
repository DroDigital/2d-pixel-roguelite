#!/usr/bin/env python3
"""Cut pixel glyphs for Chinese and Japanese from Fusion Pixel Font (SIL OFL 1.1, by TakWolf) for exactly the
characters the translations use, and write them to src/game/lang/glyphs.js in the game's font format.

The 8 px font sits beside the 5 px "mini" font, the 10 px one beside the 7 px "big" font; their baselines line up.
Fusion Pixel draws on a 100-unit grid per pixel, so each pixel is read by testing its centre against the outlines.

    pip install fonttools brotli
    python3 tools/cjk-glyphs.py          (downloads the fonts from npm the first time)

Run it again whenever zh.js or ja.js gain characters; node tools/i18n-check.mjs reports any that are missing.
"""
import json, os, re, sys, tarfile, io, urllib.request
from fontTools.ttLib import TTFont
from fontTools.pens.pointInsidePen import PointInsidePen

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
CACHE = os.path.join(ROOT, "node_modules", ".cache", "fusion-pixel")
PKG = "https://registry.npmjs.org/@fontsource/fusion-pixel-{n}px-proportional-{s}/-/fusion-pixel-{n}px-proportional-{s}-5.3.0.tgz"
# (font size in px, the game font it sits beside, that font's bottom row)
SIZES = {"mini": (8, 4), "big": (10, 6)}
SCRIPT = {"zh": "sc", "ja": "jp"}


def font(n, s):
    path = os.path.join(CACHE, f"{n}-{s}.woff2")
    if not os.path.exists(path):
        os.makedirs(CACHE, exist_ok=True)
        data = urllib.request.urlopen(PKG.format(n=n, s=s)).read()
        with tarfile.open(fileobj=io.BytesIO(data)) as tar:
            m = next(m for m in tar.getmembers() if m.name.endswith("-latin-400-normal.woff2"))
            open(path, "wb").write(tar.extractfile(m).read())
    return TTFont(path)


def chars_of(lang):
    src = open(os.path.join(ROOT, "src", "game", "lang", f"{lang}.js"), encoding="utf8").read()
    vals = re.findall(r':\s*("(?:\\.|[^"\\])*"),?\s*$', src, re.M)
    text = "".join(json.loads(v) for v in vals)
    return sorted({c for c in text if ord(c) > 0x2000})


def cut(f, chars, bottom):
    gs, cmap, U = f.getGlyphSet(), f.getBestCmap(), 100
    raw = {}
    for ch in chars:
        name = cmap.get(ord(ch))
        if not name:
            sys.exit(f"no glyph for {ch!r} (U+{ord(ch):04X})")
        adv = round(f["hmtx"][name][0] / U)
        ink = {}
        for yb in range(-3, 12):
            for x in range(adv):
                pen = PointInsidePen(gs, ((x + 0.5) * U, (yb + 0.5) * U))
                gs[name].draw(pen)
                if pen.getResult():
                    ink[(x, yb)] = True
        raw[ch] = (adv, ink)
    ys = [y for _, ink in raw.values() for (_, y) in ink]
    top, low = max(ys), min(ys)
    out = []
    for ch, (adv, ink) in raw.items():
        right = max([x for (x, _) in ink] + [0]) + 1
        w = max(adv - 1, right)
        rows = []
        for yb in range(top, low - 1, -1):
            bits = sum(1 << x for x in range(w) if ink.get((x, yb)))
            rows.append(format(bits, "x"))
        # the font's pixel row yb sits on game row bottom - yb
        out.append(f"{ch}:{w},{bottom - top}," + ",".join(rows))
    return "|".join(out)


def main():
    sets = {}
    for lang, s in SCRIPT.items():
        cs = chars_of(lang)
        sets[lang] = {f: cut(font(n, s), cs, b) for f, (n, b) in SIZES.items()}
        print(f"{lang}: {len(cs)} characters")
    # the languages' own names, shown in every language's options menu
    names = {}
    for f, (n, b) in SIZES.items():
        names[f] = cut(font(n, "sc"), sorted(set("简体中文")), b) + "|" + cut(font(n, "jp"), sorted(set("日本語")), b)
    sets["names"] = names
    body = json.dumps(sets, ensure_ascii=False, indent=1)
    head = ("// Generated by tools/cjk-glyphs.py from Fusion Pixel Font (SIL Open Font License 1.1, (c) TakWolf):\n"
            "// pixel glyphs for exactly the Chinese and Japanese characters the translations use. Do not edit by hand.\n")
    open(os.path.join(ROOT, "src", "game", "lang", "glyphs.js"), "w", encoding="utf8").write(head + "export const CJK = " + body + ";\n")


main()
